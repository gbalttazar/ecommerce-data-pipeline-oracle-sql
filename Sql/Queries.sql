SELECT 
    TO_CHAR(P.DT_PEDIDO,'YYYY-MM') AS MES,
    SUM(IP.VALOR_TOTAL_ITEM_PEDIDO) AS RECEITA
FROM T_PEDIDO P
JOIN T_ITEM_PEDIDO IP
    ON P.ID_PEDIDO = IP.ID_PEDIDO
GROUP BY TO_CHAR(P.DT_PEDIDO,'YYYY-MM')
ORDER BY MES;