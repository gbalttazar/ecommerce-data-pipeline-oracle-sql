SELECT *
FROM (
    SELECT 
        C.ID_CLIENTE,
        COUNT(P.ID_PEDIDO) AS TOTAL_PEDIDOS,
        SUM(IP.VALOR_TOTAL_ITEM_PEDIDO) AS TOTAL_GASTO
    FROM T_CLIENTE C
    JOIN T_PEDIDO P
        ON C.ID_CLIENTE = P.ID_CLIENTE
    JOIN T_ITEM_PEDIDO IP
        ON P.ID_PEDIDO = IP.ID_PEDIDO
    GROUP BY C.ID_CLIENTE
    ORDER BY TOTAL_GASTO DESC
)
WHERE ROWNUM <= 10;

