SELECT 
    ROUND(AVG(VALOR_PEDIDO),2) AS TICKET_MEDIO
FROM (
    SELECT 
        ID_PEDIDO,
        SUM(VALOR_TOTAL_ITEM_PEDIDO) AS VALOR_PEDIDO
    FROM T_ITEM_PEDIDO
    GROUP BY ID_PEDIDO
);

